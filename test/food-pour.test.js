import test from 'node:test';
import assert from 'node:assert/strict';
import * as THREE from 'three';
import { createPourEffect } from '../food-pour.js';

test('a pour reveals its deposited surface, follows rotation, and releases only owned resources', () => {
  const material = new THREE.MeshStandardMaterial({ color: 0x874b18 });
  const geometry = new THREE.SphereGeometry(1, 12, 8);
  const layer = new THREE.Group();
  layer.name = 'syrup';
  layer.position.set(.3, .8, -.2);
  layer.scale.set(.6, .1, .7);
  const surface = new THREE.Mesh(geometry, material);
  layer.add(surface);
  const parent = new THREE.Group();
  parent.add(layer);
  let sourceDisposed = false, materialDisposed = false, effectDisposed = false;
  geometry.addEventListener('dispose', () => { sourceDisposed = true; });
  material.addEventListener('dispose', () => { materialDisposed = true; });
  const pour = createPourEffect(THREE, layer);
  parent.add(pour.effect);
  surface.material.addEventListener('dispose', () => { effectDisposed = true; });
  assert.notEqual(surface.material, material, 'clipping never mutates shared template materials');
  assert.equal(surface.geometry, geometry);
  pour.update(.25);
  const plane = surface.material.clippingPlanes[0];
  const deposited = layer.localToWorld(new THREE.Vector3(-.9, 0, 0));
  const future = layer.localToWorld(new THREE.Vector3(.9, 0, 0));
  assert.ok(plane.distanceToPoint(deposited) > 0);
  assert.ok(plane.distanceToPoint(future) < 0);
  assert.equal(pour.effect.visible, true);
  parent.rotation.y = .8;
  pour.update(.5);
  assert.ok(plane.distanceToPoint(layer.localToWorld(new THREE.Vector3(-.9, 0, 0))) > 0, 'clip plane rotates with the dish');
  assert.ok(plane.distanceToPoint(layer.localToWorld(new THREE.Vector3(.9, 0, 0))) < 0);
  pour.update(1);
  assert.equal(pour.effect.visible, false);
  assert.equal(surface.material.clippingPlanes.length, 0, 'finished sauce is fully visible');
  pour.dispose();
  assert.equal(effectDisposed, true);
  assert.equal(sourceDisposed, false);
  assert.equal(materialDisposed, false);
  assert.equal(pour.effect.parent, null);
  geometry.dispose(); material.dispose();
});
